"""Phase 15: clean-install distribution tests (opt-in).

These tests build the wheel, install it into a fresh virtual environment
outside the repository, and drive the **installed** distribution with
``PYTHONPATH`` scrubbed -- so a source checkout can never masquerade as a
working install. Dependency installation needs network, so the whole
module is gated behind ``RUN_DISTRIBUTION_TESTS=1``; in a normal offline
session these tests are collected and skipped.

Distribution artifact policy: the **wheel** is the clean-install target;
the sdist is a build/existence gate only (checked in the phase's local
run, not installed anywhere).
"""

from __future__ import annotations

import os
import subprocess
import sys
import venv
import zipfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent.parent

RUN = os.environ.get("RUN_DISTRIBUTION_TESTS") == "1"

pytestmark = [
    pytest.mark.distribution,
    pytest.mark.skipif(
        not RUN, reason="set RUN_DISTRIBUTION_TESTS=1 to run clean-install tests"
    ),
]

FORBIDDEN_ROOT_FILES = {
    # repository-root modules (shims and dev files) that must never ship
    "main.py",
    "tier1_classifier.py",
    "confidence_router.py",
    "tier2_llm_handler.py",
    "packaging_and_validation.py",
    "make_fixtures.py",
    "pytest.ini",
    "requirements.txt",
    "project_context.txt",
    "applicationLayer_context.txt",
    "applicationLayer+fixing_&_addingLibraries_context.txt",
}


def _clean_env() -> dict[str, str]:
    """The environment a consumer would have: no source-tree path leaks."""
    env = dict(os.environ)
    env.pop("PYTHONPATH", None)
    env.pop("PYTHONHOME", None)
    return env


def _venv_python(venv_dir: Path) -> Path:
    return (
        venv_dir / "Scripts" / "python.exe"
        if sys.platform == "win32"
        else venv_dir / "bin" / "python"
    )


def _console_script(venv_dir: Path) -> Path:
    name = "pdf2epub.exe" if sys.platform == "win32" else "pdf2epub"
    directory = venv_dir / ("Scripts" if sys.platform == "win32" else "bin")
    return directory / name


def _run(cmd, *, cwd: Path, check: bool = True):
    proc = subprocess.run(
        [str(part) for part in cmd],
        cwd=str(cwd),
        env=_clean_env(),
        capture_output=True,
        text=True,
        check=False,
    )
    if check:
        assert proc.returncode == 0, (
            f"command failed: {cmd}\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
        )
    return proc


@pytest.fixture(scope="module")
def built_wheel(tmp_path_factory):
    out = tmp_path_factory.mktemp("dist")
    _run([sys.executable, "-m", "build", "--wheel", "--outdir", str(out)], cwd=ROOT)
    wheels = list(out.glob("pdf2epub-*.whl"))
    assert len(wheels) == 1, wheels
    return wheels[0]


@pytest.fixture(scope="module")
def clean_venv(tmp_path_factory, built_wheel):
    venv_dir = tmp_path_factory.mktemp("venv")
    venv.EnvBuilder(
        with_pip=True, symlinks=(sys.platform != "win32")
    ).create(venv_dir)
    proc = subprocess.run(
        [str(_venv_python(venv_dir)), "-m", "pip", "install", str(built_wheel)],
        capture_output=True,
        text=True,
        check=False,
        env=_clean_env(),
    )
    assert proc.returncode == 0, proc.stderr
    return venv_dir


@pytest.fixture(scope="module")
def smoke_pdf(clean_venv, tmp_path_factory):
    """Generated BY THE VENV's own pymupdf: stays inside the install boundary."""
    out = tmp_path_factory.mktemp("smoke")
    pdf = out / "smoke.pdf"
    code = (
        "import pymupdf, sys;"
        "doc = pymupdf.open();"
        "page = doc.new_page();"
        "page.insert_text((72, 72), 'A clean install smoke test page.');"
        "doc.save(sys.argv[1]);"
    )
    _run([_venv_python(clean_venv), "-c", code, str(pdf)], cwd=out)
    assert pdf.exists()
    return pdf


# -- attributes of the shipped artifact --------------------------------------

def test_wheel_contains_only_the_package(built_wheel):
    with zipfile.ZipFile(built_wheel) as zf:
        names = zf.namelist()
        tops = {name.split("/")[0] for name in names}
        assert "pdf2epub" in tops
        assert all(top == "pdf2epub" or top.endswith(".dist-info") for top in tops)

        # path-aware: the forbidden set applies to WHEEL-ROOT files only --
        # the engine modules, with the same basenames as the root shims,
        # must live INSIDE the package (positive check below)
        root_files = {name for name in names if "/" not in name}
        assert not (FORBIDDEN_ROOT_FILES & root_files), FORBIDDEN_ROOT_FILES & root_files
        assert not any(name.startswith("tests/") for name in names)
        assert not any("__pycache__" in name for name in names)

        # the engine ships inside the package, and only there
        assert "pdf2epub/engine/tier1_classifier.py" in names
        assert "pdf2epub/engine/driver.py" in names
        assert "pdf2epub/engine/packaging_and_validation.py" in names

        metadata = zf.read(
            next(n for n in names if n.endswith(".dist-info/METADATA"))
        ).decode("utf-8")
        assert "Name: pdf2epub" in metadata

        entry_points = zf.read(
            next(n for n in names if n.endswith(".dist-info/entry_points.txt"))
        ).decode("utf-8")
        assert "pdf2epub = pdf2epub.__main__:main" in entry_points


def test_import_resolves_into_the_venv_site_packages(clean_venv, tmp_path):
    code = "import pdf2epub, sys; sys.stdout.write(pdf2epub.__file__)"
    proc = _run([_venv_python(clean_venv), "-c", code], cwd=tmp_path)
    assert "site-packages" in proc.stdout
    assert str(clean_venv) in proc.stdout


def test_version_matches_installed_metadata(clean_venv, tmp_path):
    code = "import importlib.metadata; print(importlib.metadata.version('pdf2epub'))"
    expected = _run([_venv_python(clean_venv), "-c", code], cwd=tmp_path).stdout.strip()
    assert expected
    proc = _run([_console_script(clean_venv), "--version"], cwd=tmp_path)
    assert proc.stdout.strip() == f"pdf2epub {expected}"


def test_help_lists_the_subcommands(clean_venv, tmp_path):
    proc = _run([_console_script(clean_venv), "--help"], cwd=tmp_path)
    for command in ("convert", "doctor", "validators", "interactive"):
        assert command in proc.stdout


# -- running the installed product from outside the repository ----------------

def test_offline_convert_outside_the_repo(clean_venv, smoke_pdf, tmp_path):
    out = tmp_path / "out.epub"
    _run(
        [
            _console_script(clean_venv), "convert", str(smoke_pdf),
            "-o", str(out), "--provider", "none", "--skip-validation", "--quiet",
            "--cache-dir", str(tmp_path / "cache"),
        ],
        cwd=tmp_path,
    )
    assert out.exists()
    with zipfile.ZipFile(out) as zf:
        assert "mimetype" in zf.namelist()

    # `python -m pdf2epub` parity, still outside the repo
    out_module = tmp_path / "out_module.epub"
    _run(
        [
            _venv_python(clean_venv), "-m", "pdf2epub", "convert", str(smoke_pdf),
            "-o", str(out_module), "--provider", "none", "--skip-validation",
            "--quiet", "--cache-dir", str(tmp_path / "cache2"),
        ],
        cwd=tmp_path,
    )
    assert out_module.exists()


def test_piped_interactive_smoke(clean_venv, tmp_path):
    proc = subprocess.run(
        [str(_console_script(clean_venv)), "interactive"],
        input="/help\n/exit\n",
        cwd=str(tmp_path),
        env=_clean_env(),
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    assert "Available commands" in proc.stdout


def test_doctor_and_validators_exit_zero_in_a_bare_venv(clean_venv, tmp_path):
    doctor = _run([_console_script(clean_venv), "doctor"], cwd=tmp_path)
    assert "OK" in doctor.stdout  # optional tools may WARN; core must be OK

    validators = _run([_console_script(clean_venv), "validators"], cwd=tmp_path)
    assert "EPUBCheck" in validators.stdout
    assert "Ace by DAISY" in validators.stdout


def test_bare_invocation_requires_a_tty_when_installed(clean_venv, tmp_path):
    # stdin must be a PIPE, not DEVNULL: on Windows the NUL device is a
    # character device, so isatty() reports True for it and the guard
    # (correctly, by its definition) lets the REPL start.
    proc = subprocess.run(
        [str(_console_script(clean_venv))],
        cwd=str(tmp_path),
        env=_clean_env(),
        input="",
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 2
    assert "terminal" in proc.stderr
